internal fun nextDuckMessage(previous:Int):Int {
    if(previous !in duckMessages.indices)return kotlin.random.Random.nextInt(duckMessages.size)
    val pick=kotlin.random.Random.nextInt(duckMessages.size-1)
    return if(previous in duckMessages.indices&&pick>=previous)pick+1 else pick
}
